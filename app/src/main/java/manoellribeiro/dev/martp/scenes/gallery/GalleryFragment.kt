import java.io.File

@AndroidEntryPoint
class GalleryFragment : Fragment() {
    private val viewModel: MainViewModel by activityViewModels()
    private lateinit var binding: FragmentGalleryBinding
    private lateinit var mapArtsAdapter: MapArtsRecyclerViewAdapter

    override fun onCreateView(
        inflater: LayoutInflater,
        container: ViewGroup?,
        savedInstanceState: Bundle?
    ): View? {
        super.onCreateView(inflater, container, savedInstanceState)
        binding = FragmentGalleryBinding.inflate(layoutInflater)
        removeStaleSketchFragments()
        // The adapter is created in setupViews, so it must exist before the first list is collected
        setupViews()
        setupObservables()
        return binding.root
    }

    /**
     * Sketch fragments are added to containers with ids generated by the adapter. When this view
     * is recreated (or the fragment is restored) those containers no longer exist, so the old
     * sketch fragments must be removed before the child fragments try to attach their views.
     */
    private fun removeStaleSketchFragments() {
        val staleSketchFragments = childFragmentManager.fragments.filterIsInstance<PFragment>()
        if (staleSketchFragments.isEmpty()) return
        childFragmentManager.beginTransaction()
            .apply { staleSketchFragments.forEach { remove(it) } }
            .commitNow()
    }

    private fun setupViews() = with(binding) {
        ViewCompat.setOnApplyWindowInsetsListener(logoIV) { v, windowInsets ->
            val insets = windowInsets.getInsets(WindowInsetsCompat.Type.systemBars())
            v.updateLayoutParams<ViewGroup.MarginLayoutParams> {
                topMargin = insets.top
            }
            WindowInsetsCompat.CONSUMED
        }

        mapArtsAdapter = MapArtsRecyclerViewAdapter(
            fragmentManager = childFragmentManager,
            onClickListener = { mapArt ->  },
            onShareButtonClickListener = { imagePath -> shareArtImage(imagePath)}
        )
        mapArtsRV.layoutManager = LinearLayoutManager(requireContext())
        mapArtsRV.adapter = mapArtsAdapter
        // The change animation briefly binds a second ViewHolder for the same art, which would
        // run two sketch fragments for it at the same time
        (mapArtsRV.itemAnimator as? SimpleItemAnimator)?.supportsChangeAnimations = false
    }

    private fun setupObservables() {
        viewLifecycleOwner.lifecycleScope.launch {
            viewModel.galleryState
                .flowWithLifecycle(viewLifecycleOwner.lifecycle, Lifecycle.State.STARTED)
                .distinctUntilChanged()
                .collect { state ->
                    when(state) {
                        GalleryUiState.EmptyList -> setupEmptyListState()
                        is GalleryUiState.Error -> setupErrorState(state.failure)
                        GalleryUiState.Loading -> setupLoadingState()
                        is GalleryUiState.NotEmptyList -> setupNotEmptyListState(state.mapArts)
                    }
                }
        }
    }

    private fun shareArtImage(imagePathLocation: String) {
        activity?.let {
            val sharingIntent = Intent(Intent.ACTION_SEND)
            sharingIntent.addFlags(Intent.FLAG_GRANT_READ_URI_PERMISSION)
            sharingIntent.type = "image/*"
            val uri = FileProvider.getUriForFile(
                it,
                it.packageName + ".provider",
                File(imagePathLocation)
            )
            sharingIntent.putExtra(Intent.EXTRA_TEXT, getString(R.string.share_art_message))
            sharingIntent.putExtra(Intent.EXTRA_STREAM, uri)
            it.startActivities(arrayOf(Intent.createChooser(sharingIntent, "Share with")))
        }
    }

    private fun setupNotEmptyListState(mapArts: List<MapArtEntity>) = with(binding) {
        emptyListTV.gone()
        errorTV.gone()
        emptyGalleryImageIV.gone()
        loadingIndicatorPB.gone()
        mapArtsRV.visible()
        mapArtsAdapter.submitList(mapArts)
    }

    private fun setupLoadingState() = with(binding) {
        mapArtsRV.gone()
        emptyListTV.gone()
        errorTV.gone()
        emptyGalleryImageIV.gone()
        loadingIndicatorPB.visible()
    }

    private fun setupErrorState(failure: Failure) = with(binding) {
        mapArtsRV.gone()
        emptyListTV.gone()
        errorTV.visible()
        emptyGalleryImageIV.gone()
        errorTV.text = getString(failure.messageToBeDisplayedToUserId)
        loadingIndicatorPB.gone()
    }

    private fun setupEmptyListState() = with(binding) {
        mapArtsRV.gone()
        emptyListTV.visible()
        emptyGalleryImageIV.visible()
        errorTV.gone()
        loadingIndicatorPB.gone()
    }
}